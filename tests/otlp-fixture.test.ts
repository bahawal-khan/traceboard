/* eslint-disable @typescript-eslint/no-explicit-any -- these tests walk decoded protobuf JSON whose shape is exactly what is under test */
import { existsSync, readFileSync } from "node:fs";
import { describe, expect, it, vi } from "vitest";
import type { EventStore, PersistResult } from "@/lib/events/store";
import { PriceBook } from "@/lib/ingest/cost";
import { UsageGate } from "@/lib/ingest/quota";
import { createOtlpTracesHandler } from "@/lib/otlp/handler";
import { eventIdForSpan } from "@/lib/otlp/ids";
import { mapOtlpTraces, OTLP_LIMITS } from "@/lib/otlp/map";
import { decodeTraceRequest } from "@/lib/otlp/proto";
import { otlpTraceRequest } from "@/lib/otlp/schema";
import { issueCtx, type ApiKeyCtx } from "@/lib/repo/tenant";

/**
 * Runs against bytes produced by the REAL OpenTelemetry Python exporter (opentelemetry-exporter-otlp-proto-http), generated by
 * `python3 scripts/gen-otlp-fixture.py` and committed as tests/fixtures/otlp/python-traces.{pb,meta.json}. Until those files
 * exist this suite is skipped, and tests/otlp-proto.test.ts (hand-built bytes) is what covers the decoder.
 */
const PB = "tests/fixtures/otlp/python-traces.pb";
const META = "tests/fixtures/otlp/python-traces.meta.json";
const present = existsSync(PB) && existsSync(META);

describe.skipIf(!present)("OTLP protobuf from the real Python exporter", () => {
  const bytes = present ? new Uint8Array(readFileSync(PB)) : new Uint8Array();
  const meta = present ? (JSON.parse(readFileSync(META, "utf8")) as {
    packages: Record<string, string>;
    request: { content_type: string; bytes: number };
    base_unix_nano: number;
    service_name: string;
    spans: Array<{ name: string; trace_id: string; span_id: string; parent_span_id: string | null; start_unix_nano: number; end_unix_nano: number; status: string }>;
  }) : null!;
  const decoded = () => {
    const r = decodeTraceRequest(bytes, OTLP_LIMITS.maxSpansPerRequest);
    if (!r.ok) throw new Error(r.reason);
    return otlpTraceRequest.parse(r.request);
  };
  const byName = (events: Array<{ name?: string }>) => Object.fromEntries(events.map((e) => [e.name, e])) as Record<string, any>;
  const baseMs = () => Math.floor(meta.base_unix_nano / 1e6);

  it("is what the exporter sends: protobuf, not empty", () => {
    expect(meta.request.content_type).toMatch(/^application\/x-protobuf/);
    expect(bytes.length).toBe(meta.request.bytes);
    expect(Object.keys(meta.packages)).toContain("opentelemetry-exporter-otlp-proto-http");
  });

  it("decodes every span with the ids, parents and names the exporter wrote", () => {
    const r = decodeTraceRequest(bytes, OTLP_LIMITS.maxSpansPerRequest);
    expect(r.ok && r.overflowSpans).toBe(0);
    const spans = (decoded().resourceSpans ?? []).flatMap((rs) => (rs.scopeSpans ?? []).flatMap((s) => s.spans ?? []));
    expect(spans).toHaveLength(meta.spans.length);
    for (const m of meta.spans) {
      const s = spans.find((x) => x.spanId === m.span_id)!;
      expect(s, m.name).toBeDefined();
      expect([s.traceId, s.name, s.parentSpanId ?? null]).toEqual([m.trace_id, m.name, m.parent_span_id]);
      expect([s.startTimeUnixNano, s.endTimeUnixNano]).toEqual([String(m.start_unix_nano), String(m.end_unix_nano)]);
    }
  });

  it("maps to the events the GenAI conventions promise", () => {
    const r = mapOtlpTraces(decoded());
    expect(r.rejected).toEqual({ over_limit: 0, bad_ids: 0, bad_time: 0, invalid: 0 });
    const e = byName(r.events);
    for (const m of meta.spans) expect(e[m.name].event_id).toBe(eventIdForSpan(m.trace_id, m.span_id));
    expect(e["chat gpt-4o"]).toMatchObject({
      kind: "llm", model: "gpt-4o-2024-08-06", provider: "openai", input_tokens: 1200, output_tokens: 80, cached_tokens: 1024, ttft_ms: 420,
      thread_id: "conv-9", latency_ms: 850, status: "ok", ts: new Date(baseMs() + 200).toISOString(),
    });
    expect(e["chat gpt-4o"].tags).toEqual(["otlp", `svc:${meta.service_name}`]);
    expect(e["chat gpt-4o"].parent_id).toBe(meta.spans.find((s) => s.name === "workflow.step")!.span_id);
    expect(e["execute_tool search"]).toMatchObject({ kind: "tool", status: "error", error: "search failed for [redacted:email]" });
    expect(e["invoke_agent support"]).toMatchObject({ kind: "agent", status: "ok" });
    expect(e["invoke_agent support"].parent_id).toBeUndefined();
    expect(e["workflow.step"].kind).toBe("custom");
    expect(e["GET /health"].kind).toBe("custom");
    expect(JSON.stringify(r.events)).not.toContain("bob@example.com");
  });

  it("the GenAI-only filter keeps the agent, its plain ancestor step, the chat and the tool; it drops only the HTTP span", () => {
    const r = mapOtlpTraces(decoded(), { genAiOnly: true });
    expect(r.events.map((e) => e.name).sort()).toEqual(["chat gpt-4o", "execute_tool search", "invoke_agent support", "workflow.step"]);
    expect(r.filtered).toBe(1);
  });

  it("the route accepts the exporter's request as sent and answers like an OTLP server", async () => {
    const NOW = baseMs() + 60_000;
    const persisted: Array<Array<Record<string, unknown>>> = [];
    const store: EventStore = {
      persist: vi.fn(async (_c: ApiKeyCtx, rows: readonly unknown[]) => {
        persisted.push([...rows] as Array<Record<string, unknown>>);
        return { inserted: rows.length, contentStored: 0, contentDropped: 0, usage: { events: rows.length, requests: 1, costMicro: 0 }, signals: { lastViewedAt: null, conserve: false }, budgets: [] } satisfies PersistResult;
      }),
    };
    const ctx = issueCtx<ApiKeyCtx>({ kind: "apiKey", ownerId: null, projectIds: ["11111111-1111-4111-8111-111111111111"], keyId: "22222222-2222-4222-8222-222222222222", scopes: ["ingest"], readOnly: false });
    const handler = createOtlpTracesHandler({
      authenticate: async () => ({ ok: true, ctx }),
      quota: new UsageGate(async () => null, { eventsPerDay: 1000, requestsPerDay: 100 }, { now: () => NOW }),
      prices: new PriceBook(async () => [{ model: "gpt-4o", inputPer1m: "2.50", outputPer1m: "10.00", cachedInputPer1m: "1.25" }], 60_000, () => NOW),
      store,
      touchKey: async () => true,
      afterResponse: () => {},
      now: () => NOW,
    });
    const res = await handler(new Request("http://localhost/api/otlp/v1/traces", { method: "POST", headers: { "content-type": meta.request.content_type, authorization: `Bearer lm_${"K".repeat(43)}` }, body: bytes as BodyInit }));
    expect([res.status, res.headers.get("content-type"), (await res.arrayBuffer()).byteLength]).toEqual([200, "application/x-protobuf", 0]);
    expect(persisted[0]!.map((r) => r.name).sort()).toEqual(["chat gpt-4o", "execute_tool search", "invoke_agent support", "workflow.step"]);
    // priced from the response model through the date-suffix lookup: (1200-1024)*2.5 + 1024*1.25 + 80*10 micro-USD
    expect(persisted[0]!.find((r) => r.name === "chat gpt-4o")!.costMicro).toBe(Math.round(176 * 2.5 + 1024 * 1.25 + 80 * 10));
  });
});

describe("fixture presence", () => {
  it.skipIf(present)("is not generated yet: run `python3 scripts/gen-otlp-fixture.py` and commit tests/fixtures/otlp/python-traces.*", () => {
    expect(present).toBe(false);
  });
});
